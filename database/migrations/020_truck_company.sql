    id                   BIGSERIAL PRIMARY KEY,
    carrier_name         TEXT NOT NULL,
    sub_carrier_name     TEXT,
    country              TEXT,
    id_logistic_carrier  TEXT NOT NULL UNIQUE,
    active               BOOLEAN DEFAULT true,
    created_at           TIMESTAMPTZ DEFAULT now(),
